-- =========================================================================
-- Brawler trophy band dimension (per-brawler trophies)
-- =========================================================================
-- Separate from trophy_band_dim above: that one bins a player's TOTAL
-- trophies (sum across all brawlers); this one bins the trophies on a
-- single brawler — a different distribution with a much lower ceiling
-- (Brawl Stars caps per-brawler progression around 1500 with diminishing
-- meta-relevance past ~2000; high outliers still happen).
--
-- Bands widen as resolution stops mattering:
--   0-1000:    500-wide  (early progression, group coarsely)
--   1000-2000: 250-wide  (middle range — most active players sit here)
--   2000-4000: 100-wide  (high-trophy meta range — finest resolution)
--   4000+:     overflow
CREATE TABLE public.brawler_trophy_band_dim (
  brawler_trophy_band_key smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  band_min                int  NOT NULL,
  band_max                int  NOT NULL,    -- inclusive upper bound
  label                   text NOT NULL UNIQUE,
  CHECK (band_min <= band_max)
);

