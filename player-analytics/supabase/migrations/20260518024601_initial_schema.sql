-- =========================================================================
-- Fact table
-- =========================================================================
CREATE TABLE public.brawler_fact (
  -- Composite grain — same physical battle has one row per participant.
  player_tag        text NOT NULL,
  battle_id         text NOT NULL,       -- degenerate dim (md5 from OLTP)

  -- Dimensional FKs.
  date_key          int      NOT NULL REFERENCES public.date_dim(date_key),
  brawler_key       smallint NOT NULL REFERENCES public.brawler_dim(brawler_key),
  battle_dim_key    smallint NOT NULL REFERENCES public.battle_dim(battle_dim_key),
  trophy_band_key   smallint          REFERENCES public.trophy_band_dim(trophy_band_key),
    -- NULL when overall_trophies is unknown (non-targeted participant —
    -- the OLTP only knows total trophies for the queried player).
  brawler_trophy_band_key smallint NOT NULL
    REFERENCES public.brawler_trophy_band_dim(brawler_trophy_band_key),
    -- Always known: brawler_trophies is required for every participant in
    -- the OLTP brawler_trophies_store (it's returned by the API for all
    -- players in the battle).

  -- Natural timestamp retained for hour-of-day slicing without a time dim.
  battle_time       timestamptz NOT NULL,

  -- Measures.
  placement         smallint,            -- -1 draw / 0 loss / 1 win / 1..10 showdown rank / NULL unknown
  overall_trophies  int,                 -- player's total trophies after battle (queried player only)
  brawler_trophies  int,                 -- per-brawler trophies after battle
  trophy_change     int NOT NULL DEFAULT 0,

  PRIMARY KEY (player_tag, battle_id)
);

-- Per-FK indexes for star-shaped filter + join queries.
CREATE INDEX brawler_fact_brawler_key_idx      ON public.brawler_fact (brawler_key);
CREATE INDEX brawler_fact_battle_dim_key_idx   ON public.brawler_fact (battle_dim_key);
CREATE INDEX brawler_fact_trophy_band_key_idx  ON public.brawler_fact (trophy_band_key);
CREATE INDEX brawler_fact_brawler_trophy_band_key_idx
  ON public.brawler_fact (brawler_trophy_band_key);
CREATE INDEX brawler_fact_date_key_idx         ON public.brawler_fact (date_key);
CREATE INDEX brawler_fact_battle_id_idx        ON public.brawler_fact (battle_id);

-- BRIN on battle_time: append-mostly time series, BRIN gives near-zero
-- maintenance cost and tight summarization for time-range scans.
CREATE INDEX brawler_fact_battle_time_brin_idx
  ON public.brawler_fact USING brin (battle_time);
