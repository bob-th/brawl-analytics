-- Star schema for cross-player brawler analytics.
--
-- Grain of brawler_fact: one row per (player_tag, battle_id). Same physical
-- battle observed in different tracked players' logs yields the SAME
-- battle_id (md5 of sorted-min tag + battle_time) and N rows in the fact
-- table — one per participant.
--
-- Loaded by a daily ETL from the OLTP project (see local/db plan.txt).
-- Lives in a separate Supabase project from the OLTP DB; access is gated
-- by Supabase role grants (default service_role only — frontend cannot
-- reach this DB).
--
-- Schema choices vs the sketch in local/db plan.txt:
--   * trophy_dim was dropped — (overall, brawler) trophies are continuous
--     measures, not dimensional attributes. Raw values are kept as measures
--     on the fact; a trophy_band_dim provides the categorical FK for
--     range-style filtering ('winrate in 90k-100k range').
--   * fact grain is explicit at (player_tag, battle_id) so per-player
--     analytics (teammate winrate, brawler picks by player band) work.
--   * placement reuses the OLTP encoding (-1 draw / 0 loss / 1 win for team
--     modes; 1-10 finish position for showdown) so showdown rank queries
--     and draws survive the warehouse round-trip.
--   * date_dim is enriched (dow / iso_week / quarter / is_weekend) to
--     unlock the slicing patterns we want.
--
-- All keys: surrogate smallint identity for dims (low cardinality), int
-- for date_key (YYYYMMDD). battle_id is kept as a natural-key degenerate
-- dim on the fact for traceability back to OLTP.


-- =========================================================================
-- Date dimension
-- =========================================================================
CREATE TABLE public.date_dim (
  date_key      int PRIMARY KEY,        -- YYYYMMDD
  full_date     date NOT NULL UNIQUE,
  year          smallint NOT NULL,
  month         smallint NOT NULL,
  day           smallint NOT NULL,
  day_of_week   smallint NOT NULL,      -- 0=Sun .. 6=Sat (Postgres extract(dow))
  iso_week      smallint NOT NULL,
  quarter       smallint NOT NULL,
  is_weekend    boolean  NOT NULL
);

-- Pre-generate dates for a 7-year window. Cheap (~2.5k rows) and removes
-- the need for the ETL to insert dates on the fly. Extend as needed.
INSERT INTO public.date_dim
  (date_key, full_date, year, month, day, day_of_week, iso_week, quarter, is_weekend)
SELECT
  to_char(d, 'YYYYMMDD')::int,
  d::date,
  EXTRACT(year     FROM d)::smallint,
  EXTRACT(month    FROM d)::smallint,
  EXTRACT(day      FROM d)::smallint,
  EXTRACT(dow      FROM d)::smallint,
  EXTRACT(week     FROM d)::smallint,
  EXTRACT(quarter  FROM d)::smallint,
  EXTRACT(dow FROM d) IN (0, 6)
FROM generate_series('2024-01-01'::date, '2030-12-31'::date, '1 day'::interval) AS d;


